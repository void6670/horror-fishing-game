// Turns src/assets/models.glb (exported from Blender) into a JS module so every build — including the
// single-file artifact and the .exe — carries the models inline.
import { readFileSync, writeFileSync } from 'node:fs';
const b64 = readFileSync('src/assets/models.glb').toString('base64');
writeFileSync('src/assets/modelsData.js', `// Generated by scripts/embed-models.mjs from models.glb. Do not edit.\nexport default 'data:model/gltf-binary;base64,${b64}';\n`);
console.log(`embedded models.glb (${(b64.length / 1024).toFixed(0)} KB base64)`);
